import assert from 'node:assert/strict';
import {readFile,writeFile} from 'node:fs/promises';
import {join} from 'node:path';
import {openSlidesPptx,saveSlidesPptx,openOpc} from '@office-ex/ooxml';
import {inspectForEditor,writeLegacyPpt,prepareSlidesSave,serializeDraft} from '@office-ex/format-service';
import {walkSlideShapes,DocumentSession} from '@office-ex/core';
import {buildSlideScene,walkSlideScene} from '@office-ex/render';
const dir=process.argv[2],source=await readFile(join(dir,'external-graphics.pptx'));
const opened=openSlidesPptx(source,'external-graphics'),model=opened.document;
const group=model.slides[0].shapes[0];assert.equal(group.type,'group');assert.equal(group.flipH,true);assert.ok(group.geometry.rotation);
const shapes=[...walkSlideShapes(model.slides[0].shapes)];
assert.deepEqual(shapes.map(s=>s.type),['group','roundRect','triangle','group','image','diamond','parallelogram','line']);
const picture=shapes.find(s=>s.type==='image'),line=shapes.find(s=>s.type==='line');
assert.deepEqual(picture.crop,{left:12500,top:10000,right:5000,bottom:0});
assert.equal(line.connector,true);assert.equal(line.flipV,true);assert.equal(line.stroke.dash,'dashDot');assert.equal(line.stroke.tail.type,'triangle');
const resource=model.resources[picture.resourceId];assert.ok(resource?.dataBase64);
assert.ok(Buffer.from(saveSlidesPptx(source,model)).equals(source));assert.throws(()=>writeLegacyPpt(model),error=>error.code==='unsupported');
const scene=buildSlideScene(new DocumentSession(model).snapshot(),model.slides[0].id);assert.equal([...walkSlideScene(scene.shapes)].length,8);
group.geometry.x+=914400;picture.crop.left=20000;line.stroke.dash='dash';line.stroke.tail={type:'arrow',width:'sm',length:'lg'};
const saved=prepareSlidesSave('pptx',serializeDraft(model),model.documentId,source);
const reopened=openSlidesPptx(saved,model.documentId),nodes=[...walkSlideShapes(reopened.document.slides[0].shapes)];
assert.equal(reopened.document.slides[0].shapes[0].geometry.x,group.geometry.x);
assert.deepEqual(nodes.find(s=>s.type==='image').crop,picture.crop);
assert.deepEqual(nodes.find(s=>s.type==='line').stroke.tail,line.stroke.tail);
assert.equal(reopened.document.resources[picture.resourceId].sha256,resource.sha256);
const before=openOpc(source).parts,after=openOpc(saved).parts;
for(const path of [...opened.native.metadataPaths,...opened.native.auxiliaryPaths,opened.native.masterPath,...opened.native.layoutPaths])assert.deepEqual(after.get(path),before.get(path),path);
await writeFile(join(dir,'external-graphics-edited.pptx'),saved);
const bad=await readFile(join(dir,'external-attached-connector.pptx'));assert.equal((await inspectForEditor(bad,'external-attached-connector.pptx','protected')).report.readOnly,true);
console.log('Independent default-template grouped vectors, cropped image, flipped dashed arrow connector: native round trip and attached connector protection pass.');
